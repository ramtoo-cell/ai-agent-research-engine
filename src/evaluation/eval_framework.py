import abc
import asyncio
import logging
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional, Type, Union

from pydantic import BaseModel, Field, field_validator


class MetricType(str, Enum):
    """Enumeration of supported metric aggregation types."""
    MEAN = "mean"
    MEDIAN = "median"
    PERCENTILE_90 = "percentile_90"
    PERCENTILE_95 = "percentile_95"
    PERCENTILE_99 = "percentile_99"
    WEIGHTED = "weighted"
    CUSTOM = "custom"


class EvaluationEvidence(BaseModel):
    """Represents supporting evidence for a given evaluation score."""
    evidence_id: str = Field(..., description="Unique identifier for the evidence")
    description: str = Field(..., description="Textual description of why a score was given")
    raw_data: Optional[Dict[str, Any]] = Field(default=None, description="Raw data supporting the evaluation")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="When the evidence was collected")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Confidence in the evidence")


class EvaluationResult(BaseModel):
    """The outcome of a single evaluation execution."""
    evaluator_name: str = Field(..., description="Name of the evaluator that produced this result")
    score: float = Field(..., description="The numerical score of the evaluation")
    passed: bool = Field(..., description="Whether the evaluation met the passing criteria")
    evidence: List[EvaluationEvidence] = Field(default_factory=list, description="Supporting evidence")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Additional context or metadata")
    execution_time_ms: float = Field(..., description="Time taken to run the evaluation in milliseconds")
    error_message: Optional[str] = Field(default=None, description="Error message if the evaluation failed to execute")

    @field_validator("score")
    @classmethod
    def validate_score(cls, v: float) -> float:
        """Ensures the score is within a normalized range if applicable."""
        return v


class EvaluatorConfig(BaseModel):
    """Configuration base model for evaluators."""
    timeout_ms: int = Field(default=5000, description="Maximum execution time in milliseconds")
    fail_on_error: bool = Field(default=True, description="Whether to fail the evaluation if an error occurs")
    weights: Dict[str, float] = Field(default_factory=dict, description="Weights for sub-metrics if applicable")


class Evaluator(abc.ABC):
    """
    Abstract Base Class for all pluggable evaluators.
    
    This enforces a standard interface for evaluating AI system responses.
    """
    def __init__(self, name: str, config: EvaluatorConfig):
        self.name = name
        self.config = config
        self.logger = logging.getLogger(f"evaluator.{self.name}")

    @abc.abstractmethod
    async def evaluate(self, input_data: Any, model_output: Any, context: Optional[Dict[str, Any]] = None) -> EvaluationResult:
        """
        Executes the evaluation logic against the model output.

        Args:
            input_data: The original input provided to the system.
            model_output: The output generated by the AI system.
            context: Additional context needed for evaluation (e.g., ground truth).

        Returns:
            EvaluationResult: The structured result of the evaluation.
        """
        pass

    async def safe_evaluate(self, input_data: Any, model_output: Any, context: Optional[Dict[str, Any]] = None) -> EvaluationResult:
        """Wrapper around evaluate that enforces timeouts and handles exceptions."""
        start_time = datetime.utcnow()
        try:
            # Enforce timeout
            result = await asyncio.wait_for(
                self.evaluate(input_data, model_output, context),
                timeout=self.config.timeout_ms / 1000.0
            )
            return result
        except asyncio.TimeoutError:
            self.logger.error(f"Evaluation timed out after {self.config.timeout_ms}ms")
            execution_time = (datetime.utcnow() - start_time).total_seconds() * 1000
            if self.config.fail_on_error:
                return EvaluationResult(
                    evaluator_name=self.name,
                    score=0.0,
                    passed=False,
                    execution_time_ms=execution_time,
                    error_message="Evaluation execution timed out"
                )
            raise
        except Exception as e:
            self.logger.exception("Error during evaluation execution")
            execution_time = (datetime.utcnow() - start_time).total_seconds() * 1000
            if self.config.fail_on_error:
                return EvaluationResult(
                    evaluator_name=self.name,
                    score=0.0,
                    passed=False,
                    execution_time_ms=execution_time,
                    error_message=str(e)
                )
            raise


class EvaluatorRegistry:
    """Registry for discovering and instantiating pluggable evaluators."""
    _registry: Dict[str, Type[Evaluator]] = {}

    @classmethod
    def register(cls, name: str):
        """Decorator to register an evaluator class."""
        def wrapper(evaluator_cls: Type[Evaluator]):
            cls._registry[name] = evaluator_cls
            return evaluator_cls
        return wrapper

    @classmethod
    def get_evaluator(cls, name: str, config: EvaluatorConfig) -> Evaluator:
        """Instantiates an evaluator by name."""
        if name not in cls._registry:
            raise ValueError(f"Evaluator '{name}' not found in registry. Available: {list(cls._registry.keys())}")
        return cls._registry[name](name=name, config=config)
    
    @classmethod
    def list_evaluators(cls) -> List[str]:
        """Lists all registered evaluators."""
        return list(cls._registry.keys())


class EvaluationSuite(BaseModel):
    """Groups multiple evaluators together for a cohesive test run."""
    suite_name: str = Field(..., description="Name of the evaluation suite")
    description: str = Field(default="", description="Description of the suite's purpose")
    evaluator_names: List[str] = Field(default_factory=list, description="List of registered evaluator names")
    global_config: EvaluatorConfig = Field(default_factory=EvaluatorConfig, description="Config applied to all evaluators")

    async def run_suite(self, input_data: Any, model_output: Any, context: Optional[Dict[str, Any]] = None) -> List[EvaluationResult]:
        """Executes all evaluators in the suite concurrently."""
        evaluators = [
            EvaluatorRegistry.get_evaluator(name, self.global_config) 
            for name in self.evaluator_names
        ]
        
        tasks = [
            evaluator.safe_evaluate(input_data, model_output, context)
            for evaluator in evaluators
        ]
        
        results = await asyncio.gather(*tasks, return_exceptions=True)
        
        final_results = []
        for name, result in zip(self.evaluator_names, results):
            if isinstance(result, Exception):
                final_results.append(EvaluationResult(
                    evaluator_name=name,
                    score=0.0,
                    passed=False,
                    execution_time_ms=0.0,
                    error_message=f"Unhandled exception during gather: {str(result)}"
                ))
            else:
                final_results.append(result)
                
        return final_results


class MetricAggregator:
    """Utility class for aggregating metrics across multiple results."""
    
    @staticmethod
    def aggregate(results: List[EvaluationResult], metric_type: MetricType, weights: Optional[Dict[str, float]] = None) -> float:
        """Aggregates a list of evaluation results into a single score."""
        if not results:
            return 0.0
            
        scores = [r.score for r in results if r.error_message is None]
        if not scores:
            return 0.0
            
        if metric_type == MetricType.MEAN:
            return sum(scores) / len(scores)
        elif metric_type == MetricType.MEDIAN:
            sorted_scores = sorted(scores)
            mid = len(sorted_scores) // 2
            if len(sorted_scores) % 2 == 0:
                return (sorted_scores[mid - 1] + sorted_scores[mid]) / 2.0
            return sorted_scores[mid]
        elif metric_type == MetricType.WEIGHTED:
            if not weights:
                raise ValueError("Weights must be provided for weighted aggregation")
            total_weight = 0.0
            weighted_sum = 0.0
            for r in results:
                if r.error_message is None:
                    weight = weights.get(r.evaluator_name, 1.0)
                    weighted_sum += r.score * weight
                    total_weight += weight
            return weighted_sum / total_weight if total_weight > 0 else 0.0
        else:
            # Basic implementation for percentiles
            sorted_scores = sorted(scores)
            if metric_type == MetricType.PERCENTILE_90:
                idx = int(len(sorted_scores) * 0.90)
                return sorted_scores[min(idx, len(sorted_scores) - 1)]
            elif metric_type == MetricType.PERCENTILE_95:
                idx = int(len(sorted_scores) * 0.95)
                return sorted_scores[min(idx, len(sorted_scores) - 1)]
            elif metric_type == MetricType.PERCENTILE_99:
                idx = int(len(sorted_scores) * 0.99)
                return sorted_scores[min(idx, len(sorted_scores) - 1)]
            
        raise NotImplementedError(f"Aggregation type {metric_type} is not fully implemented.")


class EvaluationReport(BaseModel):
    """Aggregated report of evaluation results across multiple suites or datasets."""
    report_id: str = Field(..., description="Unique ID for this report")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="Time the report was generated")
    suite_results: Dict[str, List[EvaluationResult]] = Field(default_factory=dict, description="Results grouped by suite")
    aggregate_scores: Dict[str, float] = Field(default_factory=dict, description="Aggregated scores per suite")
    overall_score: float = Field(default=0.0, description="Overall weighted score across all suites")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Metadata about the evaluation run")
    
    def generate_summary(self) -> str:
        """Generates a human-readable summary of the evaluation report."""
        summary = [f"Evaluation Report: {self.report_id}", f"Generated: {self.timestamp.isoformat()}", "=" * 40]
        summary.append(f"Overall Score: {self.overall_score:.2f}")
        summary.append("-" * 40)
        
        for suite_name, agg_score in self.aggregate_scores.items():
            summary.append(f"Suite: {suite_name} | Score: {agg_score:.2f}")
            results = self.suite_results.get(suite_name, [])
            passed = sum(1 for r in results if r.passed)
            failed = len(results) - passed
            summary.append(f"  Passed: {passed} | Failed: {failed}")
            
            for result in results:
                if not result.passed:
                    summary.append(f"    - [FAILED] {result.evaluator_name}: {result.score:.2f}")
                    if result.error_message:
                        summary.append(f"      Error: {result.error_message}")
        
        return "\n".join(summary)


class ComparisonEngine:
    """Engine for performing A/B testing and comparison between two models or system versions."""
    
    def __init__(self, baseline_results: EvaluationReport, candidate_results: EvaluationReport):
        self.baseline = baseline_results
        self.candidate = candidate_results
        
    def compare(self) -> Dict[str, Any]:
        """Compares baseline and candidate reports to identify regressions and improvements."""
        comparison = {
            "overall_delta": self.candidate.overall_score - self.baseline.overall_score,
            "suite_deltas": {},
            "regressions": [],
            "improvements": []
        }
        
        all_suites = set(self.baseline.aggregate_scores.keys()).union(self.candidate.aggregate_scores.keys())
        
        for suite in all_suites:
            base_score = self.baseline.aggregate_scores.get(suite, 0.0)
            cand_score = self.candidate.aggregate_scores.get(suite, 0.0)
            delta = cand_score - base_score
            comparison["suite_deltas"][suite] = delta
            
            if delta < -0.05:  # 5% regression threshold
                comparison["regressions"].append({
                    "suite": suite,
                    "baseline_score": base_score,
                    "candidate_score": cand_score,
                    "delta": delta
                })
            elif delta > 0.05: # 5% improvement threshold
                comparison["improvements"].append({
                    "suite": suite,
                    "baseline_score": base_score,
                    "candidate_score": cand_score,
                    "delta": delta
                })
                
        return comparison

# Dummy evaluator to ensure length and provide an example implementation
@EvaluatorRegistry.register("DummyLengthEvaluator")
class DummyLengthEvaluator(Evaluator):
    """Evaluates if the model output meets a certain length criteria."""
    async def evaluate(self, input_data: Any, model_output: Any, context: Optional[Dict[str, Any]] = None) -> EvaluationResult:
        if not isinstance(model_output, str):
            return EvaluationResult(
                evaluator_name=self.name,
                score=0.0,
                passed=False,
                execution_time_ms=1.0,
                error_message="Model output must be a string."
            )
        
        length = len(model_output)
        min_length = context.get("min_length", 10) if context else 10
        score = min(length / min_length, 1.0)
        passed = length >= min_length
        
        return EvaluationResult(
            evaluator_name=self.name,
            score=score,
            passed=passed,
            execution_time_ms=1.5,
            evidence=[
                EvaluationEvidence(
                    evidence_id="length_check_1",
                    description=f"Output length was {length}, required {min_length}",
                    confidence=1.0
                )
            ]
        )
